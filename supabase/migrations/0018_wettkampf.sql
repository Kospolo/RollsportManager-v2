-- ============================================================================
-- 0018_wettkampf.sql — RollsportManager v2 — Wettkampf-Tiefe (Referenz §3.2:
-- wettkampf-live.html, wettkampf-modus.html, verbandsmeldung.html,
-- kuer-share.html).
--
-- Builds on 0004 (routines / competitions / competition_entries /
-- routine_scores). Two things:
--
--   1. routine_scores gains `placement` — the Live-Scoring surface records a
--      final rank alongside technical/components/total (all four already exist
--      from 0004; only placement is new). Nullable, positive.
--
--   2. routine_shares — a Kür can be shared via an opaque, revocable token
--      (kuer-share.html). RLS mirrors Referenz 1.3:
--        * read  (normal, logged-in club view) = is_club_member
--        * write (create link / revoke)        = is_club_trainer
--      The PUBLIC token view is NOT served through this RLS-client. An
--      unauthenticated visitor has no claims at all, so the API resolves the
--      token in SERVICE MODE (services/api/routes/public-routines.ts) and
--      returns ONLY the minimal, non-personal Kür payload (title, discipline,
--      music meta, markers, scores, club name) — never skater identities,
--      contact data or finance. A revoked/expired/unknown token → 404.
--
-- Enforcement is server-side (Blueprint risk #16, Referenz 1.5). The API
-- impersonates the caller (src/db.ts withUser) for the logged-in paths, so
-- these policies apply to every API write exactly as to a direct PostgREST one.
--
-- NB: seed data (routine_shares tokens + placements on the Kreispokal scores)
-- lives in supabase/seed/seed.sql — migrations run BEFORE the seed, so
-- app.clubs / app.routines are still empty here (same convention as 0016/0017).
-- ============================================================================

begin;

-- ----------------------------------------------------------------------------
-- 1. routine_scores.placement — final rank of a Kür at a competition.
--    technical_score / components_score / total_score / competition_id already
--    exist (migration 0004); this ALTER only adds the missing placement.
-- ----------------------------------------------------------------------------
alter table app.routine_scores
  add column placement integer
    constraint routine_scores_placement_positive check (placement is null or placement > 0);

-- ----------------------------------------------------------------------------
-- 2. routine_shares — opaque, revocable share tokens for a Kür.
--    token: URL-safe, high-entropy, generated by the API (gen_random_bytes in
--    the seed / crypto.randomBytes at runtime). UNIQUE so a token resolves to
--    at most one share. expires_at NULL = never expires (kuer-share "Nie").
-- ----------------------------------------------------------------------------
create table app.routine_shares (
  id                   uuid primary key default app.uuid_v7(),
  club_id              uuid not null references app.clubs (id) on delete restrict,
  routine_id           uuid not null references app.routines (id) on delete cascade,
  token                text not null unique,
  created_by_member_id uuid references app.club_members (id) on delete set null,
  expires_at           timestamptz,          -- NULL = never
  revoked              boolean not null default false,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  deleted_at           timestamptz
);

create index routine_shares_club_idx    on app.routine_shares (club_id);
create index routine_shares_routine_idx on app.routine_shares (routine_id);

create trigger routine_shares_set_updated_at
  before update on app.routine_shares
  for each row execute function app.set_updated_at();

-- ----------------------------------------------------------------------------
-- RLS — read = member, write (create/revoke) = trainer. There is deliberately
-- NO policy that lets an anon role read this table: the public token view is
-- resolved in service mode by the API, which returns only the minimal payload.
-- ----------------------------------------------------------------------------
alter table app.routine_shares enable row level security;

create policy routine_shares_select on app.routine_shares
  for select to authenticated
  using (app.is_club_member(club_id));

create policy routine_shares_insert on app.routine_shares
  for insert to authenticated
  with check (app.is_club_trainer(club_id));

create policy routine_shares_update on app.routine_shares
  for update to authenticated
  using (app.is_club_trainer(club_id))
  with check (app.is_club_trainer(club_id));

commit;
