/** Höchster Rang, den die Skala einer Fähigkeit kennt (app.cap_max_rank, 0032). */
export function capMaxRank(allowedLevels: readonly CapabilityLevel[]): number {
  return allowedLevels.reduce((max, l) => Math.max(max, LEVEL_RANK[l]), 0);
}

