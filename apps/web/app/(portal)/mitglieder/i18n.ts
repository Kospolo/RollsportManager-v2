export type MitgliederKey = keyof (typeof mitgliederDict)["de"];

/** Rolle → Dictionary-Key der Rollen-Beschriftung. */
export function roleKey(role: MemberRole): MitgliederKey {
  switch (role) {
    case "owner":
      return "roleOwner";
    case "admin":
      return "roleAdmin";
    case "treasurer":
      return "roleTreasurer";
    case "coach":
      return "roleCoach";
    case "guest_coach":
      return "roleGuest";
    default:
      return "roleMember";
  }
}
